#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=__dirname;
const html=fs.readFileSync(path.join(root,'index.html'),'utf8');
const css=fs.readFileSync(path.join(root,'art-gallery.css'),'utf8');
const pwa=fs.readFileSync(path.join(root,'pwa.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.webmanifest'),'utf8'));
const shared=path.join(root,'../shared');
assert.match(html,/href="\.\.\/shared\/demo-doi\.css"/,'Zenodo badge stylesheet missing');
assert.match(html,/src="\.\.\/shared\/demo-doi\.js"/,'Zenodo badge logic missing');
assert.match(html,/href="\.\.\/shared\/demo-support\.css"/,'Support stylesheet missing');
assert.match(html,/src="\.\.\/shared\/demo-support\.js"/,'Support menu logic missing');
const doiScript=fs.readFileSync(path.join(shared,'demo-doi.js'),'utf8');
const supportScript=fs.readFileSync(path.join(shared,'demo-support.js'),'utf8');
assert.match(doiScript,/data-demo-doi-pill/,'Zenodo DOI control is not wired');
assert.match(supportScript,/githubSponsorUrl/,'Support menu is not wired');
assert.match(supportScript,/coffeeUrl/,'Coffee support link missing');
assert.match(html,/href="\.\.\/" class="back-demos"/,'Back to demos navigation missing');
assert.match(html,/id="installApp"/,'Install PWA control missing');
assert.match(html,/id="installDialog"/,'Install app dialog missing');
assert.match(html,/id="installInstructions"/,'Install instructions target missing');
assert.match(pwa,/beforeinstallprompt/,'PWA install handler missing');
assert.match(pwa,/showInstructions\(\)/,'Browser install guidance missing');
assert.equal(manifest.display,'standalone');
assert.match(css,/\.install-dialog/,'Install dialog needs compact artwork-theme styling');
assert.match(css,/@media\(max-width:390px\)\{\s*\.site-header nav\{display:flex/,'Important header controls must remain accessible on small screens');
assert.doesNotMatch(html,/onlinepilatesclasses|instructor|biomechanical|anatomy assessment|classical pilates/i,'Gallery must remain art-only');
console.log('MetaForma project controls PASS: Zenodo pending badge, Support menu, All Demos links, responsive Install app dialog and PWA logic');
