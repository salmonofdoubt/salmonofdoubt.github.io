const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'../demos/envai');
const file=(name)=>fs.readFileSync(path.join(root,name),'utf8');
const {items}=JSON.parse(file('data/tools.json'));
const usable=t=>['online','install','access'].includes(t.toolUse);
const visible=items.filter(usable);
assert.equal(items.length,52);
assert.equal(visible.length,25);
assert.equal(items.filter(t=>t.toolUse==='reference').length,27);
assert.equal(visible.filter(t=>t.mapVisible!==false).length,25);
assert(visible.every(t=>!/(^|\.)github\.com\//.test(new URL(t.url).hostname+'/')));
assert(visible.every(t=>new URL(t.url).protocol==='https:'));
assert(visible.every(t=>t.baselineEntry));
assert.equal(visible.find(t=>t.id==='qgis').toolUse,'install');
assert.equal(visible.find(t=>t.id==='trace').url,'https://climatetrace.org/explore');
assert.equal(visible.find(t=>t.id==='openaq').url,'https://explore.openaq.org/');
assert(!visible.some(t=>t.id==='glen'||t.id==='orcai'||t.id==='speciesnet'));
for(const name of ['Biodiversity & wildlife','Land & satellites','Climate & energy','Water & oceans'])assert(visible.some(t=>t.domain===name));
const context={console,URL};vm.createContext(context);vm.runInContext(file('semantic-search.js'),context);
const index=context.EnvAISemantic.prepare(visible);
const whale=context.EnvAISemantic.search(index,'whales',6);
assert.equal(whale.dominantDomain,'Water & oceans');
assert(whale.hits.length>0);
assert(whale.hits.some(h=>['whalemap','happywhale'].includes(h.tool.id)));
assert(!whale.hits.some(h=>h.tool.toolUse==='reference'));
const bird=context.EnvAISemantic.search(index,'bird',6);
assert.equal(bird.dominantDomain,'Biodiversity & wildlife');
const empty=context.EnvAISemantic.search(index,'nonexistingweirdterm12345',6);
assert.equal(empty.hits.length,0);
for(const f of ['app.js','whats-new.js','how-it-works.js']){
 const source=file(f);assert(source.includes('toolUse'));}
assert(file('whats-new.js').includes('!t.baselineEntry'));
assert(file('app.js').includes('&&publicTool(t)'));
assert(file('live-data.js').includes("toolUse:'online',mapVisible:false"));
assert(file('service-worker.js').includes('sod-envai-v21-practical-tools'));
console.log('PASS: 52 transparent reference records, 25 public tools, 27 hidden research references');
console.log('PASS: no GitHub-only destinations, all four domains, direct explorer URLs, semantic whale/bird search, no seed-news clutter');
